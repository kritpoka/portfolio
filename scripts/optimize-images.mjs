// Optimizes source screenshots into public/work/<slug>/ and writes content/media.ts.
//
//   node scripts/optimize-images.mjs
//
// Originals live in sources/assets/ (gitignored). Outputs are WebP at a sensible
// max width; next/image then serves AVIF/WebP at the size each layout needs.
// Never add the KU Map landmark photos (other photographers' work) or anything ttb.

import { mkdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import sharp from "sharp";

const SRC = "sources/assets";
const OUT = "public/work";

// Phone screenshots from the POS (1170×2532): drop the iOS status bar and the
// Safari address bar, keep the app's own header and tab bar.
const POS_CROP = { top: 150, bottom: 2370 };

/** key → [source file, slug, output name, max width, crop?] */
const IMAGES = {
  kuMapShare: ["ku-campus-map/og-share.jpg", "ku-campus-map", "og-share", 1200],
  kuMapShuttle: ["ku-campus-map/final-desktop-shuttle-line1.jpg", "ku-campus-map", "desktop-shuttle", 960],
  kuMapSearch: ["ku-campus-map/final-desktop-search.jpg", "ku-campus-map", "desktop-search", 960],
  kuMapFilters: ["ku-campus-map/final-desktop-filters-food-sport.jpg", "ku-campus-map", "desktop-filters", 960],
  kuMapCard: ["ku-campus-map/cards-1440-landmark-card.jpg", "ku-campus-map", "desktop-place-card", 1280],
  kuMapMobileSearch: ["ku-campus-map/final-mobile-search-sheet-375.jpg", "ku-campus-map", "mobile-search", 750],
  kuMapMobileShuttle: ["ku-campus-map/final-mobile-shuttle-390x844.jpg", "ku-campus-map", "mobile-shuttle", 780],
  posOrdering: ["kasetfair-pos/ordering.png", "kasetfair-pos", "ordering", 780, POS_CROP],
  posCart: ["kasetfair-pos/cart.png", "kasetfair-pos", "cart", 780, POS_CROP],
  posDashboard: ["kasetfair-pos/dashboard.png", "kasetfair-pos", "dashboard", 780, POS_CROP],
  posProducts: ["kasetfair-pos/product-list.png", "kasetfair-pos", "product-list", 780, POS_CROP],
  posEdit: ["kasetfair-pos/edit.png", "kasetfair-pos", "edit", 780, POS_CROP],
};

const entries = [];
for (const [key, [file, slug, name, maxWidth, crop]] of Object.entries(IMAGES)) {
  let img = sharp(join(SRC, file));
  if (crop) {
    const { width } = await img.metadata();
    img = sharp(await img.extract({ left: 0, top: crop.top, width, height: crop.bottom - crop.top }).toBuffer());
  }
  const resized = await img.resize({ width: maxWidth, withoutEnlargement: true }).toBuffer();
  await mkdir(join(OUT, slug), { recursive: true });
  const out = join(OUT, slug, `${name}.webp`);
  const { width, height } = await sharp(resized).webp({ quality: 86 }).toFile(out);
  const blur = await sharp(resized).resize(16).webp({ quality: 40 }).toBuffer();
  entries.push(
    `  ${key}: { src: "/work/${slug}/${name}.webp", width: ${width}, height: ${height}, blurDataURL: "data:image/webp;base64,${blur.toString("base64")}" },`,
  );
  console.log(out, `${width}×${height}`);
}

await writeFile(
  "content/media.ts",
  `// Generated by scripts/optimize-images.mjs — do not edit by hand.
import type { StaticImageData } from "next/image";

export const media = {
${entries.join("\n")}
} satisfies Record<string, StaticImageData>;
`,
);
